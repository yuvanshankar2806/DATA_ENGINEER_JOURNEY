# for loop syntax

for variable in sequence:
    # code block to be executed for each item in the sequence
    print(variable)

# understanding the for loop syntax range function

for i in range(5):
    print(i)

# range function with start and end values

for i in range(2, 6):
    print(i)

# range function with start, end, and step values

for i in range(2, 11, 2):
    print(i)

