# Print number 1 to 5

i = 1

while i <= 5:
    print(i)
    i += 1

# Print even numbers

i = 2

while i <= 10:
    print(i)
    i += 2

# Countdown Series

i = 5

while i >= 1:
    print(i)
    i -= 1

print("Done!")

# Print Continuous series

while True:
    print("Hello")

# Break statement

i = 1

while i <= 10:
    if i == 6:
        break
    print(i)
    i += 1

# Continue statement

i = 0

while i < 5:
    i += 1

    if i == 3:
        continue

    print(i)

# Nested while loop

i = 1

while i <= 3:
    j = 1

    while j <= 3:
        print("i =", i, "j =", j)
        j += 1

    i += 1



